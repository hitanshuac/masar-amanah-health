/**
 * Maps patient ID to active SOP protocol ID
 */
export const PATIENT_TO_SOP: Record<string, string> = {
  'MALAFFI-PT-001': 'SOP-03',
  'MALAFFI-PT-002': 'SOP-05',
  'MALAFFI-PT-003': 'SOP-06',
  'MALAFFI-PT-004': 'SOP-04',
  'MALAFFI-PT-005': 'SOP-02',
  'MALAFFI-PT-006': 'SOP-01',
};

/**
 * Returns the active SOP protocol for a given patient ID
 */
export function getSopForPatient(patientId: string): SOPProtocol {
  const sopId = PATIENT_TO_SOP[patientId] || 'SOP-01';
  return SOP_REGISTRY[sopId] || SOP_REGISTRY['SOP-01'];
}

/**
 * Map numeric workbench step (1..4) to SOAP step key ('S' | 'O' | 'A' | 'P')
 */
export function stepNumberToSoapKey(stepNumber: number): SoapStepKey {
  switch (stepNumber) {
    case 1:
      return 'S';
    case 2:
      return 'O';
    case 3:
      return 'A';
    case 4:
      return 'P';
    default:
      return 'S';
  }
}

/**
 * Map SOAP step key to numeric workbench step
 */
export function soapKeyToStepNumber(key: SoapStepKey): number {
  switch (key) {
    case 'S':
      return 1;
    case 'O':
      return 2;
    case 'A':
      return 3;
    case 'P':
      return 4;
  }
}

/**
 * Formats the entire SOP protocol library into an XML block for AI Co-Pilot prompt injection
 */
export function formatSopLibraryForPrompt(): string {
  const sops = Object.values(SOP_REGISTRY);
  const items = sops
    .map(
      (sop) => `  <sop id="${sop.id}" patient="${sop.patientId}" category="${sop.category}">
    <title>${sop.titleEn}</title>
    <phase>${sop.encounterPhase}</phase>
    <objective>${sop.clinicalObjectiveEn}</objective>
    <steps>
      <s gate="${sop.steps.S.gateCheckLabelEn}">${sop.steps.S.expectedDirectiveEn} Predicted: ${sop.steps.S.predictedOutcomeEn}</s>
      <o gate="${sop.steps.O.gateCheckLabelEn}">${sop.steps.O.expectedDirectiveEn} Predicted: ${sop.steps.O.predictedOutcomeEn}</o>
      <a gate="${sop.steps.A.gateCheckLabelEn}">${sop.steps.A.expectedDirectiveEn} Predicted: ${sop.steps.A.predictedOutcomeEn} Unexpected Pivot: ${sop.steps.A.unexpectedOutcomeEn}</a>
      <p gate="${sop.steps.P.gateCheckLabelEn}">${sop.steps.P.expectedDirectiveEn} Predicted: ${sop.steps.P.predictedOutcomeEn}</p>
    </steps>
  </sop>`
    )
    .join('\n');

  return `<sop_protocol_library>\n${items}\n</sop_protocol_library>`;
}

